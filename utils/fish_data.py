#    순발행 = (10회 × 1회 기댓값) − 낚시대값 = 20.2 − 10 = **약 +10코인/일**.
#    상한이 사람당 하루로 딱 정해져서 **총 발행량이 예측 가능**해요. 1차 설계에선
#    불가능했던 일이에요.
#
# 🚨 **발행을 줄이려면 `ROD_PRICE`를 올리세요.** 이제 이게 유일하고 확실한 손잡이예요
#    (물고기 값을 내리는 것보다 직관적이고, 상점 소각도 같이 늘어요).
#
# ⚠️ 타이밍을 놓쳐도 내구도는 **줄어들어요**(사용자 결정). 안 그러면 낚시대 하나가
