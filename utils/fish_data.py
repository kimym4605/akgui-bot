# 치수를 굴릴 때 쓰는 최빈값 위치. 0.3이면 작은 쪽에 몰려서 **큰 놈이 드물어요.**
# 1.0으로 두면 균등분포가 되고 대물급이 너무 흔해져요.
SIZE_SKEW = 0.3


def roll_size(key: str, rng=None) -> int:
    """이 어종의 치수(cm)를 굴려요. 작은 쪽으로 치우친 삼각분포예요.

    ⚠️ 균등분포로 두면 "최대 크기 피라미"가 너무 자주 나와서 기록의 의미가 없어져요."""
    import random as _random

    rng = rng or _random
    lo, hi = SIZE_BY_KEY.get(key, (1, 1))
    if hi <= lo:
        return lo
    return int(round(rng.triangular(lo, hi, lo + (hi - lo) * SIZE_SKEW)))


def pieces_of(key: str, size: int | None = None) -> int:
    """이 물고기의 값(**조각**). 치수가 클수록 비싸요.

    `size`가 None이면 그 어종의 **중앙 크기**로 봐요 - 치수 시스템 이전에 잡아둔
    물고기(어항에 `{key: 마리수}`로만 남아있는 것)를 평가할 때 써요."""
    grade = BY_KEY.get(key, (None, None))[0]
    if not grade:
        return 0
    lo_p, hi_p = GRADES[grade]["pieces"]
    lo_s, hi_s = SIZE_BY_KEY.get(key, (1, 1))
    if size is None:
        size = (lo_s + hi_s) / 2
    if hi_s <= lo_s:
        return lo_p
    ratio = min(1.0, max(0.0, (size - lo_s) / (hi_s - lo_s)))
    return int(round(lo_p + (hi_p - lo_p) * ratio))


def expected_pieces_per_cast(rarity_factor: float = 1.0) -> float:
    """1회 던질 때 평균 몇 **조각**이 생기나 (타이밍은 맞혔다고 가정).

    ⚠️ 등급 안에서 치수가 **작은 쪽으로 치우쳐** 있어서(`SIZE_SKEW`), 단순히
    범위의 중앙값을 쓰면 과대평가예요. 삼각분포의 평균은 `(lo+hi+mode)/3`이에요.

    `rarity_factor`는 8차 몰아 던지기 벌칙이에요. 기본 1.0 = 수동 한 판 기준이라
    **기존 호출부는 그대로 맞아요.**"""
    weights = grade_weights(rarity_factor)
    total_w = sum(weights.values())
    out = 0.0
    for grade, g in GRADES.items():
        lo, hi = g["pieces"]
        mode = lo + (hi - lo) * SIZE_SKEW
        out += weights[grade] / total_w * (lo + hi + mode) / 3
    return out


def expected_coin_per_cast(rarity_factor: float = 1.0) -> float:
    """1회 던질 때 평균 몇 코인이 생기나 (타이밍은 맞혔다고 가정)."""
    return expected_pieces_per_cast(rarity_factor) / COIN_PIECES


def batch_coin_per_cast(casts: int) -> float:
    """몰아 던질 때 **1캐스트당** 평균 코인. 안내문·리포트가 쓰는 자리예요.

    ⭐ 묶음 크기가 수익을 바꾸는 **유일한 경로**가 이 함수예요(치수·미스는 안 건드려요)."""
    return expected_coin_per_cast(batch_rarity_factor(casts))


def expected_coin_per_day() -> float:
    """낚시대 하나를 다 쓰면 하루에 얼마가 생기나 (낚시대값 제외 전)."""
    return expected_coin_per_cast() * ROD_DURABILITY


def net_issue_per_rod() -> float:
    """낚시대 1개(내구도를 다 쓰면)당 순발행.

    ⚠️ **이건 더 이상 1인 하루 상한이 아니에요.** 6차에서 상한이 낚시대 개수가 아니라
    **던진 횟수**로 옮겨갔어요(`DAILY_CAST_CAP`). 하루 발행 상한을 알고 싶으면
    `max_daily_net_issue()`를 쓰세요 — 이 함수로 추정하면 상한을 넘겨 잡아요."""
    return expected_coin_per_day() - ROD_PRICE


def net_issue_per_cast() -> float:
    """캐스트 1회당 순발행 = (1회 기댓값 − 캐스트 1회당 낚시대값).

    ⭐ 낚시대값은 큰 것도 소형도 **1코인/캐스트**라(비율을 일부러 맞춰뒀어요) 어느
    낚시대를 쓰든 이 값이 같아요. 비율을 깨면 이 함수가 거짓이 돼요."""
    return expected_coin_per_cast() - ROD_PRICE / ROD_DURABILITY


def batch_rarity_factor(casts: int) -> float:
    """몰아 던진 횟수에 따른 **희귀 이상 가중치 배수**. 1회(수동)면 1.0이에요. (8차)

    🚨 `BATCH_RARITY_FLOOR`에서 멈춰요. 바닥이 없으면 크게 몰아 던질 때 희귀가
    0에 수렴해서 "몰아 던지면 쓰레기만 나온다"가 돼요 — 그럼 아무도 안 써요.
    ⚠️ `BATCH_RARITY_FLOOR`를 0으로 두면 벌칙을 끄는 게 아니라 **희귀를 전멸**시켜요.
       끄려면 `BATCH_RARITY_PENALTY`를 0으로 하세요."""
    if casts <= 1 or not BATCH_RARITY_PENALTY:
        return 1.0
    return max(BATCH_RARITY_FLOOR, 1.0 - BATCH_RARITY_PENALTY * (casts - 1))


def grade_weights(rarity_factor: float = 1.0) -> dict[str, float]:
    """등급별 추첨 가중치. `rarity_factor < 1`이면 **희귀 이상만** 깎아요. (8차)

    ⭐ 깎은 몫을 `COMMON_GRADE`에 더하지 않아요 — `random.choices`가 가중치를
    알아서 정규화하니, 희귀 쪽만 줄이면 그만큼 확률이 일반으로 **저절로** 옮겨가요.
    (더하면 이중으로 반영돼요.)
    🚨 **꽝을 만들지 않아요.** 1차 설계의 꽝 60%는 1회당 수익만 낮추고 총 발행은
    못 막았어요 — 되살리지 마세요."""
    return {
        grade: (info["weight"] if grade == COMMON_GRADE
                else info["weight"] * rarity_factor)
        for grade, info in GRADES.items()
    }


def grade_chance(rarity_factor: float = 1.0) -> dict[str, float]:
    """등급별 **확률**(0~1). 안내문이 쓰라고 뺐어요 — 손으로 계산하지 마세요."""
    w = grade_weights(rarity_factor)
    total = sum(w.values())
    return {g: v / total for g, v in w.items()} if total else {g: 0.0 for g in w}


def streak_cast_bonus(streak: int) -> int:
    """연속 출석 `streak`일로 얻는 **추가 캐스트 횟수**. (7차)

    🚨 `STREAK_CAST_MAX`에서 멈춰요 — 그게 발행 천장이에요.
    ⚠️ `streak`은 **살아있는 연속**이어야 해요(끊긴 기록은 0으로 넘기세요).
       판정은 `fishing_store._streak_sync`가 해요.
    ⚠️ `DAILY_CAST_CAP`이 0(무제한)이면 보너스는 의미가 없으니 0이에요."""
    if streak <= 0 or not DAILY_CAST_CAP or not STREAK_CAST_EVERY:
        return 0
    return min(STREAK_CAST_MAX, (streak // STREAK_CAST_EVERY) * STREAK_CAST_BONUS)


def daily_cap_for(streak: int) -> int:
    """그 사람의 **하루 캐스트 상한**. 0이면 무제한이에요.

    🚨 상한을 쓰는 곳은 전부 이 함수를 거쳐야 해요. `DAILY_CAST_CAP`을 직접 비교하면
    7차 보너스를 무시하고 20에서 막아버려요(`fishing_store`의 조건부 update 포함)."""
    if not DAILY_CAST_CAP:
        return 0
    return DAILY_CAST_CAP + streak_cast_bonus(streak)


def max_daily_net_issue(streak: int = 0) -> float:
    """🚨 **1인 하루 순발행 상한.** 6차부터 경제에 실제로 더해질 수 있는 최대치예요.

    ⚠️ 기본값은 **연속 보너스 없음**(=기본 상한 20회)이에요. 7차에서 기본값을 천장으로
       바꾸려다 말았는데, 그러면 "하루 20번을 다 쓰면 N코인" 식으로 쓰고 있던 안내문
       7곳이 **조용히 과장**돼요(평범한 사람이 버는 액수가 아니게 돼요).
       경제 전체의 천장이 필요하면 `ceiling_daily_net_issue()`를 쓰세요.

    `DAILY_CAST_CAP`이 0(무제한)이면 상한이 없다는 뜻이라 `inf`를 줘요 — 0을 주면
    "발행이 없다"로 잘못 읽혀요."""
    if not DAILY_CAST_CAP:
        return float("inf")
    return daily_cap_for(streak) * net_issue_per_cast()


def ceiling_daily_net_issue() -> float:
    """🚨 **경제의 1인 하루 발행 천장** = 연속 보너스를 다 받은 사람 기준(7차).

    발행이 어디까지 갈 수 있나를 볼 땐 이걸 보세요. `max_daily_net_issue()`는
    보너스가 없는 사람 기준이라 **천장을 낮게 잡아요.**"""
    if not DAILY_CAST_CAP:
        return float("inf")
    return (DAILY_CAST_CAP + STREAK_CAST_MAX) * net_issue_per_cast()


def income_for_cap(cap: int) -> float:
    """상한이 `cap`회인 사람이 그걸 다 쓰면 **버는 총액**(낚시대값 빼기 전).

    ⭐ 7차부터 상한이 사람마다 달라서, 안내문은 `DAILY_CAST_CAP`이 아니라
    `fishing_store.cast_quota()`가 준 `cap`으로 계산해야 맞아요. 수식을 호출부에
    복사하지 않게 이 함수를 거치세요."""
    if not cap:
        return float("inf")
    return cap * expected_coin_per_cast()


def max_daily_income(streak: int = 0) -> float:
    """상한을 다 쓴 사람이 하루에 **버는 총액**(낚시대값을 빼기 전).

    ⚠️ `max_daily_net_issue`와 같은 이유로 기본값은 **연속 보너스 없음**이에요."""
    if not DAILY_CAST_CAP:
        return float("inf")
    return income_for_cap(daily_cap_for(streak))


