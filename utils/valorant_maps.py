"""발로란트 맵 목록이에요. `/맵추천`과 내전 맵 기록이 같은 목록을 써요.

원래 `cogs/map.py` 안에만 있었는데, 내전 결과에 맵을 남기게 되면서 두 곳에서 필요해졌어요.
cog가 다른 cog를 import하는 모양을 피하려고 여기로 옮겼어요.

⚠️ 맵 로테이션은 시즌마다 바뀌어요. 새 맵이 들어오거나 빠지면 **여기만** 고치면 돼요.
⚠️ 이름을 바꾸면 이미 쌓인 내전 기록의 맵 이름과 어긋나서 맵별 전적이 둘로 쪼개져요.
   (`scrim_matches.map`에 이름 문자열이 그대로 들어가요) 이름 변경은 신중하게.
"""

MAPS = [
    "어센트", "바인드", "브리즈", "프랙처", "헤이븐",
    "아이스박스", "로터스", "펄", "스플릿", "선셋", "어비스", "코로드",
]

# 디스코드 Select 컴포넌트는 옵션을 25개까지만 담을 수 있어요.
MAX_SELECT_OPTIONS = 25


def is_known(name: str | None) -> bool:
    """지금 로테이션에 있는 맵 이름인지. 빠진 맵의 옛 기록도 보여주긴 해야 해서
    조회 쪽에서 걸러내는 용도로는 쓰지 않아요(표시 순서를 정할 때만 써요)."""
    return bool(name) and name in MAPS


def sort_key(name: str) -> tuple[int, str]:
    """맵 목록 순서대로 정렬하되, 로테이션에서 빠진 옛 맵은 뒤로 보내요."""
    try:
        return (0, f"{MAPS.index(name):02d}")
    except ValueError:
        return (1, name)
